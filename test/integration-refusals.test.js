import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fixture,invoice,bill,receipt } from './integration-fixtures.js';
test('every refusal class leaves financial tables unchanged',async()=>{
  const f=await fixture();
  const snapshot=async()=>({books:await f.books(),catalog:await Promise.all(['customer','vendor','item'].map(t=>f.count(t)))});
  const reject=async(path,body,status)=>{const before=await snapshot();assert.equal((await f.api(path,body)).status,status);assert.deepEqual(await snapshot(),before);};
  try{
    await reject('/invoices',{...invoice(),customer_name:'Sample missing'},422);
    await reject('/bills',{...bill(),vendor_name:'Sample missing'},422);
    await reject('/bills',{...bill(),lines:[{account_name:'Sample missing',amount_cents:10000}]},422);
    await reject('/invoices',{...invoice(),source:'other_connector'},422);
    await reject('/invoices',{...invoice(),entity_id:f.ids.entityB},422);
    await reject('/invoices',{...invoice(),txn_date:'2026-02-30'},422);
    await reject('/invoices',{...invoice(),txn_date:'2026-10-20'},409);
    await f.pool.query(`INSERT INTO customer(org_id,entity_id,display_name) VALUES($1,$2,'Sample only B')`,[f.S.orgId,f.ids.entityB]);
    await reject('/invoices',{...invoice(),customer_name:'Sample only B'},422);
    await reject('/invoices',{...invoice(),terms_name:'Sample missing'},422);
    await reject('/invoices',{...invoice(),total_cents:-1},422);
    await reject('/invoices',{...invoice(),due_date:'2026-10-20'},422);
    await reject('/invoices',{...invoice(),lines:[]},422);
    await reject('/invoices',{...invoice(),doc_number:'X'.repeat(31)},422);
    await reject('/invoices',{...invoice(),source_ref:''},422);
    await reject('/invoices',{...invoice(),source_ref:'x'.repeat(201)},422);
    await reject('/customer-payments',{...receipt(),amount_cents:0},422);
    await reject('/customer-payments',{...receipt(),reference:'x'.repeat(51)},422);
    const missingAccount=receipt();delete missingAccount.deposit_to_account_name;
    await reject('/customer-payments',missingAccount,422);
    await reject('/customer-payments',receipt('raw-id',[{txn_id:1,amount_cents:10000}]),422);
    await reject('/customer-payments',receipt('both',[{source_ref:'invoice:1',doc_number:'INV-1',amount_cents:10000}]),422);
    await f.pool.query(`INSERT INTO sales_settings(org_id,entity_id,custom_numbers) VALUES($1,$2,false)
      ON CONFLICT(org_id,entity_id) DO UPDATE SET custom_numbers=false`,[f.S.orgId,f.S.entityId]);
    await reject('/invoices',invoice(),409);
    await f.pool.query('UPDATE sales_settings SET custom_numbers=true WHERE entity_id=$1',[f.S.entityId]);
    await f.pool.query('UPDATE account SET active=false WHERE account_id=$1',[f.ids.income]);
    await reject('/invoices',invoice(),422);
    await f.pool.query('UPDATE account SET active=true WHERE account_id=$1',[f.ids.income]);
    await f.pool.query('UPDATE customer SET active=false WHERE customer_id=$1',[f.ids.customerId]);
    await reject('/invoices',invoice(),422);
    await f.pool.query('UPDATE customer SET active=true,currency=\'CAD\' WHERE customer_id=$1',[f.ids.customerId]);
    await reject('/invoices',invoice(),422);
    await f.pool.query('UPDATE customer SET currency=null WHERE customer_id=$1',[f.ids.customerId]);
    await f.pool.query("UPDATE item SET kind='inventory' WHERE item_id=$1",[f.ids.itemId]);
    await reject('/invoices',invoice(),422);
    await f.pool.query("UPDATE item SET kind='product' WHERE item_id=$1",[f.ids.itemId]);
    const bp={source_ref:'ap:1',vendor_name:'Sample vendor A',txn_date:'2026-10-22',amount_cents:10000,method:'Other',reference:'AP-1',bank_account_name:'Checking',applications:[{source_ref:'bill:1',amount_cents:10000}]};
    assert.equal((await f.api('/bills',{...bill(),approve:false})).status,201);
    await reject('/bill-payments',bp,422);
    await f.pool.query("UPDATE txn SET approval_status='approved' WHERE type='bill'");
    await reject('/bill-payments',{...bp,method:'Wire'},422);
    await reject('/bill-payments',{...bp,method:'Check'},422);
    await reject('/bill-payments',{...bp,method:'Check',check_no:'ABC'},422);
    await reject('/bill-payments',{...bp,applications:[{source_ref:'bill:1',amount_cents:10000,applied_on:'2026-10-23'}]},422);
    await reject('/bill-payments',{...bp,check_no:'1042'},422);
    await reject('/bill-payments',{...bp,bank_account_name:'Sample missing'},422);
    await f.pool.query('UPDATE vendor SET bank_verified=false WHERE vendor_id=$1',[f.ids.vendorId]);
    await reject('/bill-payments',{...bp,method:'ACH'},422);
    await f.pool.query('UPDATE vendor SET bank_verified=true WHERE vendor_id=$1',[f.ids.vendorId]);
    assert.equal((await f.api('/bill-payments',{...bp,method:'Check',check_no:'1042'})).status,201);
    assert.equal((await f.api('/bills',bill('2'))).status,201);
    await reject('/bill-payments',{...bp,source_ref:'ap:2',method:'Check',check_no:'1042',applications:[{source_ref:'bill:2',amount_cents:10000}]},422);
    await f.pool.query('UPDATE integration_setting SET write_floor=null WHERE entity_id=$1',[f.S.entityId]);
    await reject('/invoices',invoice(),403);
    await f.revoke();await reject('/invoices',invoice(),401);
  }finally{await f.close();}
});
