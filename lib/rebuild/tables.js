// Public ordinary tables that none of the four sets name — a new migration must add its table here before a rebuild runs.
export async function classifyTables(db) {
  const { rows } = await db.query("SELECT relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY 1");
  const known = new Set([...IMPORTER_TABLES, ...KEPT_TABLES, ...TRANSIENT_TABLES, ...CARRIED_TABLES]);
  return rows.map(r => r.relname).filter(t => !known.has(t));
}
